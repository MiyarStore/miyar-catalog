def _settext(p, text):
    ts = list(p.iter(qn("w:t")))
    ts[0].text = text
    for t in ts[1:]:
        t.text = ""

def insert_cover(D, girls, title, sub, who):
    src = _Doc(_COVER[girls])
    els = [copy.deepcopy(e) for e in list(src.element.body)[:8]]
    for blip in els[0].iter(qn("a:blip")):
        rid = blip.get(qn("r:embed"))
        part = src.part.related_parts[rid]
        blip.set(qn("r:embed"), D.d.part.relate_to(part, _RT.IMAGE))
    _settext(els[5], title)
    _settext(els[7], who)
    if sub:
        s2 = copy.deepcopy(els[6]); _settext(s2, sub)
        for sp_ in els[6].iter(qn("w:spacing")):
            sp_.set(qn("w:before"), "200")
        seq = els[:6] + [s2] + els[6:]
    else:
        seq = els
    sp = D.body.find(qn("w:sectPr"))
    for e in seq:
        sp.addprevious(e)

