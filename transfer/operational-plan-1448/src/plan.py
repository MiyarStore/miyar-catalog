    def merge(t, rows):
        spans = []; start = None
        for i, r in enumerate(rows):
            if r[0] != "":
                if start is not None: spans.append((start, i - 1))
                start = i
        spans.append((start, len(rows) - 1))
        for a0, a1 in spans:
            if a1 == a0: continue
            for col in (0, 1):
                for ri in range(a0, a1 + 1):
                    pr = t.rows[ri + 1].cells[col]._tc.get_or_add_tcPr()
                    vm = OxmlElement("w:vMerge")
                    if ri == a0: vm.set(qn("w:val"), "restart")
                    tw = pr.find(qn("w:tcW")); gs = pr.find(qn("w:gridSpan"))
                    anchor = gs if gs is not None else tw
                    if anchor is not None: anchor.addnext(vm)
                    else: pr.insert(0, vm)
            for ri in range(a0, a1):
                for p in t.rows[ri + 1].cells[2]._tc.iter(qn("w:p")):
                    ppr = p.find(qn("w:pPr"))
                    if ppr is None:
                        ppr = OxmlElement("w:pPr"); p.insert(0, ppr)
                    if ppr.find(qn("w:keepNext")) is None:
                        ps = ppr.find(qn("w:pStyle")); kn = OxmlElement("w:keepNext")
                        if ps is not None: ps.addnext(kn)
                        else: ppr.insert(0, kn)

    def weekly(S, base, sem, groups, titles, notes):
        for gi, ((lo, hi), tt) in enumerate(zip(groups, titles)):
            D.section("الخطة الأسبوعية للفصل الدراسي " + sem, tt)
            rows = []
            for (ci, lab, items) in S[lo:hi]:
                h, gg = wk(ci, base)
                if lab is None:
                    s0 = base + dt.timedelta(weeks=ci, days=-2)
                    n = 9 if "الخريف" in items else 16
                    e0 = s0 + dt.timedelta(days=n - 1)
                    hs = Gregorian(s0.year, s0.month, s0.day).to_hijri(); he = Gregorian(e0.year, e0.month, e0.day).to_hijri()
                    hh = f"{a(hs.day)} {HM[hs.month]} - {a(he.day)} {HM[he.month]}" if hs.month != he.month else f"{a(hs.day)} - {a(he.day)} {HM[he.month]}"
                    gg2 = f"{a(s0.day)} {GM[s0.month]} - {a(e0.day)} {GM[e0.month]}" if s0.month != e0.month else f"{a(s0.day)} - {a(e0.day)} {GM[e0.month]}"
                    rows.append(["-", hh + "\n" + gg2, items, "-", "-", "-", "-"])
                    continue
                for k, (prog, lev, tgt, exe) in enumerate(items):
                    first = k == 0
                    rows.append([a(lab) if first else "", (h + "\n" + gg) if first else "", prog, lev, tgt, exe, "☐"])
            t = D.table(["الأسبوع", "التاريخ", "البرنامج أو الخدمة", "المستوى", "المستهدفون", "المنفذ", "تم"],
                    rows, [0.95, 1.6, 3.8, 1.0, 1.55, 1.7, 0.4], size=9.5,
                    aligns=["center", "center", "right", "center", "center", "center", "center"], zebra=False)
            merge(t, rows)
            for k, r in enumerate(rows):
                if r[0] == "-":
                    for c in t.rows[k + 1].cells:
                        D._shade(c, LIGHT)
            if gi in notes:
                D.note(notes[gi], size=10)
            br()

