def wk(i, base=None):
    s = (base or B1) + dt.timedelta(weeks=i)
    e = s + dt.timedelta(days=4)
    hs = Gregorian(s.year, s.month, s.day).to_hijri(); he = Gregorian(e.year, e.month, e.day).to_hijri()
    h = f"{a(hs.day)} {HM[hs.month]}" + (f" - {a(he.day)} {HM[he.month]}" if hs.month != he.month else f" - {a(he.day)}")
    h = (f"{a(hs.day)} - {a(he.day)} {HM[he.month]}" if hs.month == he.month else f"{a(hs.day)} {HM[hs.month]} - {a(he.day)} {HM[he.month]}")
    g = (f"{a(s.day)} - {a(e.day)} {GM[e.month]}" if s.month == e.month else f"{a(s.day)} {GM[s.month]} - {a(e.day)} {GM[e.month]}")
    return h, g

