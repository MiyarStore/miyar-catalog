function guessStandard(text, role) {
  const t = String(text || '');
  const list = forRole(role);
  let best = { id: list[3] ? list[3].id : list[0].id, score: 0 };
  for (const s of list) {
    let score = 0;
    for (const k of s.keywords) if (t.includes(k)) score += k.length > 4 ? 2 : 1;
    if (score > best.score) best = { id: s.id, score };
  }
  return best.id;
}

