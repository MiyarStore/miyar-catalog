function guessStandard(text) {
  const t = String(text || '');
  let best = { id: 4, score: 0 };
  for (const s of STANDARDS) {
    let score = 0;
    for (const k of s.keywords) if (t.includes(k)) score += k.length > 4 ? 2 : 1;
    if (score > best.score) best = { id: s.id, score };
  }
  return best.id;
}

const byId = (id) => STANDARDS.find((s) => s.id === Number(id));

module.exports = { STANDARDS, guessStandard, byId };
