// مستويات التقدير العام للأداء (الدليل الإرشادي، الإصدار الثاني)
const BANDS = [
  { score: 5, name: 'مثالي' },
  { score: 4, name: 'تخطى التوقعات' },
  { score: 3, name: 'وافق التوقعات' },
  { score: 2, name: 'بحاجة إلى تطوير' },
  { score: 1, name: 'غير مرضٍ' },
];
// التقدير العام = مجموع (تقدير العنصر × وزنه النسبي)، فيطلع رقم من 1 إلى 5، ومستواه أقرب درجة صحيحة
const band = (v) => BANDS.find((b) => b.score === Math.min(5, Math.max(1, Math.round(v))));
const levelsOf = (id) => LEVELS[Number(id)] || null;

// تنظيف التقديرات المحفوظة: {عنصر: 1..5}
function clean(r, role) {
  const ids = new Set(forRole(role).map((s) => s.id));
  const out = {};
  for (const [k, v] of Object.entries(r || {})) { const n = Math.round(Number(v)); if (ids.has(Number(k)) && n >= 1 && n <= 5) out[k] = n; }
  return out;
}
// آلية الاحتساب: تقدير العنصر (1-5) × وزنه النسبي، ثم جمع التقديرات الموزونة.
// إذا ما اكتمل التقدير نحسب على العناصر المقدّرة فقط (نعيد توزيع الأوزان) ونوضح ذلك.
function calc(role, ratings) {
  const list = forRole(roleKey(role));
  const r = clean(ratings, role);
  const rows = list.map((s) => ({ id: s.id, no: s.no, name: s.name, weight: s.weight, score: r[s.id] || 0, weighted: r[s.id] ? (r[s.id] * s.weight) / 100 : 0, levels: levelsOf(s.id) }));
  const rated = rows.filter((x) => x.score);
  const wRated = rated.reduce((a, x) => a + x.weight, 0);
  const sum = rated.reduce((a, x) => a + x.weighted, 0);
  const value = wRated ? Math.round(((sum * 100) / wRated) * 100) / 100 : 0;
  const b = rated.length ? band(value) : null;
  return { rows, rated: rated.length, total: rows.length, complete: rated.length === rows.length, value, band: b, weightRated: wRated };
}

module.exports = { LEVELS, BANDS, band, levelsOf, clean, calc };
