// للوظائف الأخرى: تقسيم آلي لوصف المستوى 5 على الفواصل
function autoSplit(text) {
  const out = [];
  for (let f of String(text || '').replace(/\.$/, '').split(/،\s*/)) {
    f = f.trim(); if (!f) continue;
    // «مما...» و«مع...» و«وقياس...» تكملة للعبارة السابقة، أما «ويستخدم» فعبارة جديدة
    if (out.length && (/^(مما|مع |بما|حتى|لت)/.test(f) || (/^و/.test(f) && !/^و[يتُ]/.test(f)))) { out[out.length - 1] += `، ${f}`; continue; }
    out.push(f.replace(/^و(?=[يتُ])/, ''));
  }
  return out.filter((t) => t.length > 8).slice(0, 6).map((t, i) => ({ k: String.fromCharCode(97 + i), t, ev: [] }));
}

function partsOf(id, role) {
  const lv = RUB.levelsOf(id, role);
  // نفس نص المستوى 5 للمعلم (مثل معلمة رياض الأطفال في العناصر المشتركة) نستخدم عباراته المحررة
  if (TEACHER[id] && lv && lv[4] === (RUB.levelsOf(id, 'teacher') || [])[4]) return TEACHER[id];
  return lv ? autoSplit(lv[4]) : [];
}

// تغطية عنصر: كل عبارة كم شاهد عليها
function coverage(parts, evs) {
  const rows = parts.map((p) => ({ ...p, n: evs.filter((e) => (e.parts || []).includes(p.k)).length }));
  return { rows, covered: rows.filter((r) => r.n).length, total: rows.length };
}

